function esc(s: string) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

// Map scanner vector → human-readable injection location
function locKey(vector?: string): string {
  switch (vector) {
    case "query": return "query";
    case "form-get": return "query";
    case "form-post": return "body";
    case "json-body": return "body";
    case "graphql": return "body";
    case "header": return "header";
    case "cookie": return "cookie";
    case "path": return "path";
    case "dom-xss": return "fragment";
    default: return "other";
  }
}

