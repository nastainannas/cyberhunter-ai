  const [cookie, setCookie] = useState("");
  const [maxPages, setMaxPages] = useState("150");
  const [maxDepth, setMaxDepth] = useState("4");
  const [requestDelay, setRequestDelay] = useState("0");
  const [maxProbes, setMaxProbes] = useState("300");
  const [includeSubdomains, setIncludeSubdomains] = useState(false);
  const [expanded, setExpanded] = useState<string | null>(null);
  const [searchParams] = useSearchParams();
  const logRef = useRef<HTMLDivElement>(null);

  // Scan progress state lives in the module-level store — it survives
  // navigating to other pages and back while a scan is still running.
  const snap = useSyncExternalStore(subscribeScan, getScanState);
  const { logs, liveFindings, results, queue, scanning, error } = snap;

  useEffect(() => {
    const t = searchParams.get("target");
    if (t) setTarget(t);
  }, [searchParams]);

  useEffect(() => {
    logRef.current?.scrollTo({ top: logRef.current.scrollHeight });
  }, [logs]);

  // One target may contain several URLs separated by newline/comma/semicolon.
  async function scanOne(t: string, multi: boolean, signal: AbortSignal): Promise<ScanResult | null> {
    const res = await fetch("/api/scan/stream", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      signal,
      body: JSON.stringify({
        target: t,
        mode,
        auth: authEnabled
          ? authKind === "cookie"
            ? { cookie }
            : { loginUrl, username, password }
          : null,
        maxPages: parseInt(maxPages, 10) || undefined,
        maxDepth: parseInt(maxDepth, 10) || undefined,
        maxProbeRequests: parseInt(maxProbes, 10) || undefined,
        requestDelayMs: parseInt(requestDelay, 10) || undefined,
        includeSubdomains,
      }),
    });
    if (!res.ok || !res.body) throw new Error(`HTTP ${res.status}`);

    const reader = res.body.getReader();
    const decoder = new TextDecoder();
    let buffer = "";
    let out: ScanResult | null = null;
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      buffer += decoder.decode(value, { stream: true });
      const lines = buffer.split("\n");
      buffer = lines.pop() ?? "";
      for (const line of lines) {
        const tl = line.trim();
        if (!tl.startsWith("data:")) continue;
        try {
          const ev = JSON.parse(tl.slice(5));
          if (ev.type === "log") {
            appendLog(multi ? `[${new URL(t).hostname}] ${ev.message}` : ev.message);
          } else if (ev.type === "finding") {
            appendLiveFinding(ev.finding);
          } else if (ev.type === "result" || ev.type === "cancelled") {
            out = ev;
            appendLog(ev.cancelled
              ? `[stopped] ${t} — scan dihentikan, ${ev.summary?.total ?? 0} partial findings (tersimpan di Findings Database)`
              : `[done] ${t} — ${ev.summary?.total ?? 0} findings (tersimpan di Findings Database)`);
          } else if (ev.type === "error") {
            setScanState({ error: ev.error || "Scan failed" });
            appendLog(`[error] ${t}: ${ev.error}`);
          }
        } catch { /* ignore partial */ }
      }
    }
    return out;
  }

  // Process the target queue sequentially; abort keeps the current target
  // at the front of the queue so "Lanjut Scan" can resume it.
  async function runQueue(multi: boolean) {
    setScanState({ scanning: true, error: null });
    abortCtrl = new AbortController();
    const signal = abortCtrl.signal;
    try {
      for (;;) {
        const q = getScanState().queue;
        if (!q.length) break;
        const t = q[0];
        try {
          const r = await scanOne(t, multi, signal);
          if (r) appendResult(r);
          shiftQueue();
        } catch (e: any) {
          if (e?.name === "AbortError" || signal.aborted) {
            appendLog("[stopped] Scan dihentikan — klik 'Lanjut Scan' untuk melanjutkan target tersisa");
            break;
          }
          setScanState({ error: e.message });
          appendLog(`[error] ${t}: ${e.message}`);
          shiftQueue();
        }
      }
    } finally {
      setScanState({ scanning: false });
    }
  }

  async function startScan() {
    const targets = target.split(/[\n,;]+/).map((s) => s.trim()).filter(Boolean);
    if (!targets.length || scanning || !authorized) return;
    resetScanView();
    appendLog(`[${new Date().toLocaleTimeString()}] Connecting to scanner…`);
    if (targets.length > 1) appendLog(`[${targets.length} targets] ${targets.join(", ")}`);
    setScanState({ queue: [...targets] });
    await runQueue(targets.length > 1);
  }

  function stopScan() {
    abortCtrl?.abort();
    appendLog("[stop] Menghentikan scan…");
  }

  async function resumeScan() {
    const q = getScanState().queue;
    if (scanning || !q.length) return;
    appendLog(`[resume] Melanjutkan ${q.length} target tersisa…`);
    await runQueue(q.length > 1 || results.length > 0);
  }

  function clearScan() {
    if (scanning) return;
    resetScanView();
    appendLog("[clear] Log dan hasil dibersihkan");
  }

